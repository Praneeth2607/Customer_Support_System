"""
Step 8: Automated Evaluation Harness

The single, consolidated entry point Hiver runs to reproduce this project's
headline results. Wraps (does not duplicate) the metric logic already built
in Steps 5-7:
  - src/classification/baselines.py:evaluate / evaluate_escalation
  - src/evaluation/evaluate_agent.py

What it does, by default (no API key, no LLM calls, finishes in well under
15 minutes):
  1. Summarizes the frozen golden set (data/golden/golden_evaluation_set.json).
  2. Regenerates the two Step 6 baselines fresh -- cheap (~1 minute), fully
     local, deterministic (fixed seed), so there's no reason not to confirm
     them live rather than trust a possibly-stale cached file.
  3. Loads the Step 7 AI agent's results from data/results/ai_agent_results.json.
     Does NOT regenerate these by default -- that requires a GOOGLE_API_KEY
     and (per Decision 13) can take 15-20+ minutes against a free-tier
     quota. Use --regenerate-agent to opt in explicitly.
  4. Loads Step 9's LLM-judge response-quality scores and human-agreement
     report from data/judge/. Also not regenerated by default for the same
     API-cost/time reason -- use --regenerate-judge to opt in.
  5. Writes one consolidated report: data/results/evaluation_report.json
     (machine-readable) and data/results/evaluation_report.md (human-readable).

Usage:
  python evaluate.py                     # fast path, uses committed results
  python evaluate.py --regenerate-agent  # also re-runs the LLM agent (slow, needs API key)
  python evaluate.py --regenerate-judge  # also re-runs the LLM judge (slow, needs API key)
"""

import argparse
import json
import os
import subprocess
import sys

GOLDEN_SET_PATH = "data/golden/golden_evaluation_set.json"
RESULTS_DIR = "data/results"
JUDGE_DIR = "data/judge"
BASELINE_COMPARISON_PATH = f"{RESULTS_DIR}/baseline_comparison.json"
BASELINE_MAJORITY_PATH = f"{RESULTS_DIR}/baseline_majority.json"
BASELINE_TFIDF_PATH = f"{RESULTS_DIR}/baseline_tfidf_logreg.json"
AGENT_RESULTS_PATH = f"{RESULTS_DIR}/ai_agent_results.json"
AGENT_METRICS_PATH = f"{RESULTS_DIR}/ai_agent_metrics.json"
SYSTEM_COMPARISON_PATH = f"{RESULTS_DIR}/system_comparison.json"
JUDGE_RESULTS_PATH = f"{JUDGE_DIR}/llm_judge_results.json"
AGREEMENT_REPORT_PATH = f"{JUDGE_DIR}/agreement_report.json"
REPORT_JSON_PATH = f"{RESULTS_DIR}/evaluation_report.json"
REPORT_MD_PATH = f"{RESULTS_DIR}/evaluation_report.md"


def load_json(path):
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def summarize_golden_set():
    golden = load_json(GOLDEN_SET_PATH)
    from collections import Counter
    intent_counts = Counter(c["gold_intent"] for c in golden)
    escalate_counts = Counter(c["should_escalate"] for c in golden)
    return {
        "path": GOLDEN_SET_PATH,
        "size": len(golden),
        "intent_distribution": dict(intent_counts),
        "escalate_true": escalate_counts.get(True, 0),
        "escalate_false": escalate_counts.get(False, 0),
    }


def run_baselines():
    print("\n[1/3] Regenerating Step 6 baselines (fresh, ~1 min, no API calls)...")
    result = subprocess.run(
        [sys.executable, "-m", "src.classification.baselines"],
        capture_output=True, text=True, timeout=180,
    )
    if result.returncode != 0:
        print(result.stdout)
        print(result.stderr)
        raise RuntimeError("Baseline regeneration failed -- see output above.")
    print("      Done.")


def ensure_agent_results(regenerate):
    if regenerate:
        print("\n[2/3] Regenerating Step 7 AI agent results (LLM calls, may take "
              "15-20+ minutes on a free-tier key)...")
        result = subprocess.run(
            [sys.executable, "-m", "src.pipeline.support_agent"],
            capture_output=True, text=True, timeout=3600,
        )
        if result.returncode != 0:
            print(result.stdout)
            print(result.stderr)
            raise RuntimeError("AI agent regeneration failed -- see output above.")
        print("      Done.")
    elif not os.path.exists(AGENT_RESULTS_PATH):
        raise FileNotFoundError(
            f"{AGENT_RESULTS_PATH} not found. This is a committed artifact of "
            f"Step 7 and should already be in the repo. To regenerate it "
            f"yourself (needs GOOGLE_API_KEY in .env, ~15-20 min): run\n"
            f"  python -m src.pipeline.support_agent\n"
            f"or re-run this harness with --regenerate-agent."
        )
    else:
        print(f"\n[2/3] Using committed Step 7 results ({AGENT_RESULTS_PATH}). "
              f"Pass --regenerate-agent to re-run the LLM agent instead.")

    print("      Scoring against gold labels...")
    result = subprocess.run(
        [sys.executable, "-m", "src.evaluation.evaluate_agent"],
        capture_output=True, text=True, timeout=60,
    )
    if result.returncode != 0:
        print(result.stdout)
        print(result.stderr)
        raise RuntimeError("Agent scoring failed -- see output above.")


def ensure_judge_results(regenerate):
    if regenerate:
        print("\n[2b/3] Regenerating Step 9 LLM-judge scores (LLM calls, may take "
              "15-20+ minutes on a free-tier key)...")
        result = subprocess.run(
            [sys.executable, "-m", "src.evaluation.llm_judge"],
            capture_output=True, text=True, timeout=3600,
        )
        if result.returncode != 0:
            print(result.stdout)
            print(result.stderr)
            raise RuntimeError("LLM judge regeneration failed -- see output above.")
        print("      Done.")
    elif not os.path.exists(JUDGE_RESULTS_PATH):
        raise FileNotFoundError(
            f"{JUDGE_RESULTS_PATH} not found. This is a committed artifact of "
            f"Step 9 and should already be in the repo. To regenerate it "
            f"yourself (needs GOOGLE_API_KEY in .env, ~15-20 min): run\n"
            f"  python -m src.evaluation.llm_judge\n"
            f"or re-run this harness with --regenerate-judge."
        )
    else:
        print(f"\n[2b/3] Using committed Step 9 judge results ({JUDGE_RESULTS_PATH}). "
              f"Pass --regenerate-judge to re-run the LLM judge instead.")

    print("      Computing human-agreement statistics...")
    result = subprocess.run(
        [sys.executable, "-m", "src.evaluation.judge_agreement"],
        capture_output=True, text=True, timeout=60,
    )
    if result.returncode != 0:
        print(result.stdout)
        print(result.stderr)
        raise RuntimeError("Judge agreement computation failed -- see output above.")


def summarize_judge_quality():
    judge_results = load_json(JUDGE_RESULTS_PATH)
    dims = ["correctness", "groundedness", "helpfulness", "safety",
            "brand_consistency", "tone"]
    means = {dim: round(sum(j[dim] for j in judge_results) / len(judge_results), 4)
             for dim in dims}
    return {"n_scored": len(judge_results), "mean_scores": means}


def build_report(golden_summary):
    baseline_comparison = load_json(BASELINE_COMPARISON_PATH)
    baseline_majority = load_json(BASELINE_MAJORITY_PATH)
    baseline_tfidf = load_json(BASELINE_TFIDF_PATH)
    agent_metrics = load_json(AGENT_METRICS_PATH)
    system_comparison = load_json(SYSTEM_COMPARISON_PATH)
    judge_quality = summarize_judge_quality()
    agreement = load_json(AGREEMENT_REPORT_PATH)

    report = {
        "golden_set": golden_summary,
        "intent_classification": {
            "majority_class_baseline": {
                "accuracy": baseline_majority["accuracy"],
                "macro_f1": baseline_majority["macro_f1"],
                "per_class": baseline_majority["per_class"],
            },
            "tfidf_logreg_baseline": {
                "accuracy": baseline_tfidf["accuracy"],
                "macro_f1": baseline_tfidf["macro_f1"],
                "per_class": baseline_tfidf["per_class"],
                "vocab_size": baseline_tfidf.get("vocab_size"),
            },
            "ai_agent": {
                "accuracy": agent_metrics["intent_classification"]["accuracy"],
                "macro_f1": agent_metrics["intent_classification"]["macro_f1"],
                "per_class": agent_metrics["intent_classification"]["per_class"],
                "model": agent_metrics.get("model"),
            },
        },
        "escalation_decision": {
            "ai_agent": agent_metrics["escalation_decision"],
            "baseline_note": (
                "Baselines have no learned escalation model -- "
                "baseline_*.json's 'escalation_supplementary' metric is a "
                "rough default-policy-lookup approximation, not a fair "
                "comparison point. The AI agent's escalation_decision above "
                "is the only real learned escalation evaluation in this project."
            ),
        },
        "headline_comparison_table": system_comparison,
        "response_quality": {
            "llm_judge_mean_scores": judge_quality,
            "human_agreement": {
                "n_examples": agreement["n_examples"],
                "pooled": agreement["pooled"],
                "primary_statistic": "mean_absolute_disagreement",
                "note": (
                    "MAD is reported as primary because some dimensions "
                    "(e.g. safety) have low score variance, making Spearman/"
                    "kappa statistically unstable there -- see Decision 16."
                ),
            },
        },
        "notes": [
            "Baselines are trained on Step 5's heuristic pseudo-labels "
            "(measured 74% agreement with true gold labels), not gold "
            "labels -- their accuracy partly reflects weak-label quality, "
            "not just model capability. See Decision 12.",
            "AI agent escalation accuracy reflects a diagnosed prompt fix "
            "(Decision 14): 76.0% -> 85.0%. Pre-fix results are preserved "
            "as data/results/ai_agent_results_v1_baseline.json for the record.",
            "Response-quality human agreement uses a single self-rater (the "
            "developer), not a diverse human pool -- see Decision 16 and "
            "docs/response_quality_rubric.md.",
        ],
    }
    return report


def render_markdown(report):
    gs = report["golden_set"]
    ic = report["intent_classification"]
    esc = report["escalation_decision"]["ai_agent"]
    cmp_table = report["headline_comparison_table"]

    lines = [
        "# Evaluation Report",
        "",
        f"**Test set**: `{gs['path']}` -- {gs['size']} hand-labelled examples, frozen.",
        f"Escalate=True: {gs['escalate_true']} | Escalate=False: {gs['escalate_false']}",
        "",
        "## Intent Classification -- Three-Way Comparison",
        "",
        "| System | Accuracy | Macro F1 |",
        "|---|---|---|",
        f"| Majority class | {ic['majority_class_baseline']['accuracy']} | "
        f"{ic['majority_class_baseline']['macro_f1']} |",
        f"| TF-IDF + Logistic Regression | {ic['tfidf_logreg_baseline']['accuracy']} | "
        f"{ic['tfidf_logreg_baseline']['macro_f1']} |",
        f"| **AI Agent ({ic['ai_agent'].get('model', 'n/a')})** | "
        f"**{ic['ai_agent']['accuracy']}** | **{ic['ai_agent']['macro_f1']}** |",
        "",
        "## AI Agent -- Escalation Decision",
        "",
        f"Accuracy: **{esc['accuracy']}** | "
        f"escalate=True F1: {esc['escalate_class_f1']} "
        f"(precision {esc['escalate_class_precision']}, recall {esc['escalate_class_recall']})",
        "",
        "## Response Quality (LLM-as-Judge)",
        "",
    ]
    rq = report["response_quality"]
    lines.append("Mean judge scores (1-5) across all "
                  f"{rq['llm_judge_mean_scores']['n_scored']} responses:")
    lines.append("")
    for dim, val in rq["llm_judge_mean_scores"]["mean_scores"].items():
        lines.append(f"- {dim}: {val}")
    lines.append("")
    pooled = rq["human_agreement"]["pooled"]
    lines.append(f"Human agreement (n={rq['human_agreement']['n_examples']} examples, "
                  f"primary statistic: {rq['human_agreement']['primary_statistic']}):")
    lines.append(f"- Mean Absolute Disagreement: {pooled['mean_absolute_disagreement']}")
    lines.append(f"- Spearman r: {pooled['spearman_r']} | "
                  f"Weighted kappa: {pooled['weighted_kappa']} | "
                  f"Exact match: {pooled['exact_match_rate']} | "
                  f"Within 1 point: {pooled['within_1_point_rate']}")
    lines.append(f"- {rq['human_agreement']['note']}")
    lines += [
        "",
        "## Notes",
        "",
    ]
    lines += [f"- {n}" for n in report["notes"]]
    lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description="Step 8: Automated Evaluation Harness")
    parser.add_argument("--regenerate-agent", action="store_true",
                         help="Re-run the Step 7 LLM agent instead of using committed results "
                              "(needs GOOGLE_API_KEY in .env; can take 15-20+ minutes)")
    parser.add_argument("--regenerate-judge", action="store_true",
                         help="Re-run the Step 9 LLM judge instead of using committed results "
                              "(needs GOOGLE_API_KEY in .env; can take 15-20+ minutes)")
    parser.add_argument("--skip-baselines", action="store_true",
                         help="Skip regenerating baselines; use whatever is already on disk")
    args = parser.parse_args()

    print("=" * 70)
    print("STEP 8: AUTOMATED EVALUATION HARNESS")
    print("=" * 70)

    golden_summary = summarize_golden_set()
    print(f"\nGolden set: {golden_summary['size']} examples "
          f"({golden_summary['escalate_true']} escalate / "
          f"{golden_summary['escalate_false']} auto-handle)")

    if not args.skip_baselines:
        run_baselines()
    else:
        print("\n[1/3] Skipping baseline regeneration (--skip-baselines)")

    ensure_agent_results(args.regenerate_agent)
    ensure_judge_results(args.regenerate_judge)

    print("\n[3/3] Building consolidated report...")
    report = build_report(golden_summary)

    os.makedirs(RESULTS_DIR, exist_ok=True)
    with open(REPORT_JSON_PATH, "w", encoding="utf-8") as f:
        json.dump(report, f, indent=2)
    markdown = render_markdown(report)
    with open(REPORT_MD_PATH, "w", encoding="utf-8") as f:
        f.write(markdown)

    print("\n" + "=" * 70)
    print("HEADLINE RESULTS")
    print("=" * 70)
    print(markdown)
    print(f"Wrote {REPORT_JSON_PATH}")
    print(f"Wrote {REPORT_MD_PATH}")


if __name__ == "__main__":
    main()
